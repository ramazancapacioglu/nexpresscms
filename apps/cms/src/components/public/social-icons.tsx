/** Bağlantının hangi sosyal ağa ait olduğunu adresinden ve etiketinden bulur (yoksa null: sosyal bağlantı değil). */
export function socialKind(href: string, label = ""): SocialKind | null {
  const hay = `${href} ${label}`.toLowerCase();
  if (/facebook\.com|fb\.com/.test(hay)) return "facebook";
  if (/(^|[/.])(x|twitter)\.com/.test(hay)) return "x";
  if (/instagram\.com/.test(hay)) return "instagram";
  if (/linkedin\.com/.test(hay)) return "linkedin";
  if (/youtube\.com|youtu\.be/.test(hay)) return "youtube";
  if (/github\.com/.test(hay)) return "github";
  if (/pinterest\./.test(hay)) return "pinterest";
  if (/wa\.me|whatsapp\.com/.test(hay)) return "whatsapp";
  return null;
}

export function SocialIcon({ kind, size = 16 }: { kind: SocialKind; size?: number }) {
  if (kind === "instagram") {
    return (
      <svg viewBox="0 0 24 24" width={size} height={size} fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" aria-hidden="true">
        <rect x="3" y="3" width="18" height="18" rx="5" />
        <circle cx="12" cy="12" r="4" />
        <circle cx="17.5" cy="6.5" r="1" fill="currentColor" stroke="none" />
      </svg>
    );
  }
  return (
    <svg viewBox="0 0 24 24" width={size} height={size} fill="currentColor" aria-hidden="true">
      <path d={PATHS[kind]} />
    </svg>
  );
}

const NAMES: Record<SocialKind, string> = { facebook: "Facebook", x: "X", instagram: "Instagram", linkedin: "LinkedIn", youtube: "YouTube", github: "GitHub", pinterest: "Pinterest", whatsapp: "WhatsApp" };

/** Yalnızca simge olarak sosyal bağlantılar (erişilebilir ad `aria-label`/`title` ile verilir). */
export function SocialIconLinks({ items, className = "" }: { items: Array<{ href: string; label: string }>; className?: string }) {
  const rows = items.map((item) => ({ ...item, kind: socialKind(item.href, item.label) })).filter((item): item is typeof item & { kind: SocialKind } => item.kind !== null);
  if (rows.length === 0) return null;
  return (
    <ul className={`nx-social-icons flex items-center gap-2 ${className}`}>
      {rows.map((item) => (
        <li key={`${item.kind}|${item.href}`}>
          <a href={item.href} target="_blank" rel="noopener noreferrer me" aria-label={NAMES[item.kind]} title={NAMES[item.kind]} className="grid h-8 w-8 place-items-center rounded-full bg-white/10 transition hover:bg-white/25">
            <SocialIcon kind={item.kind} />
          </a>
        </li>
      ))}
    </ul>
  );
}
