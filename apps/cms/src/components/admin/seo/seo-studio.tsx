"use client";

import React, { useState, useTransition } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import type { ContentType, PermalinkStructure, SeoEngineSettings } from "@nexpress/core";
import { saveSeoEngineSettingsAction } from "@/app/admin/actions";
import { fieldClass } from "@/components/admin/appearance/appearance-ui";
import { WebmasterPanel } from "./webmaster-panel";
import { BotPolicyPanel } from "./bot-policy-panel";
import { contentTypeLabel, type SeoSummary } from "./seo-summary";

const TYPES: Array<{ id: ContentType; label: string }> = [
  { id: "page", label: "Sayfa" },
  { id: "post", label: "Yazı" },
  { id: "kb_tech", label: "Bilgi bankası" },
  { id: "ai_prompt", label: "Soru" },
  { id: "product", label: "Ürün" },
  { id: "campaign", label: "Kampanya" },
];

const TOGGLES: Array<{ key: keyof SeoEngineSettings; label: string }> = [
  { key: "autoDescription", label: "Boş açıklamayı kısa yanıttan veya ilk paragraftan üret" },
  { key: "autoCanonical", label: "Canonical adresi otomatik yaz" },
  { key: "autoRedirectOnSlugChange", label: "Adres değişince eski URL için 301 tut" },
  { key: "autoSchema", label: "SSS, adım ve inceleme bloklarından şema üret" },
  { key: "enableLlmsTxt", label: "/llms.txt ve Markdown uçlarını açık tut" },
  { key: "noIndexTagArchives", label: "Etiket arşivlerini noindex tut" },
  { key: "enableIndexNow", label: "IndexNow tercihini açık tut" },
];

export function SeoStudio({
  initial,
  summary,
  siteName,
}: {
  initial: SeoEngineSettings;
  summary: SeoSummary;
  siteName: string;
}) {
  const router = useRouter();
  const [tab, setTab] = useState<"summary" | "settings">("summary");
  const [seo, setSeo] = useState(initial);
  const [notice, setNotice] = useState<string | null>(null);
  const [pending, start] = useTransition();

  const patch = (next: Partial<SeoEngineSettings>) => setSeo((prev) => ({ ...prev, ...next }));

  const save = () => {
    start(async () => {
      const sameAs = seo.sameAs.map((item) => item.trim()).filter(Boolean);
      const res = await saveSeoEngineSettingsAction({
        seo: {
          ...seo,
          sameAs,
          separator: seo.titleSeparator || seo.separator,
          autoGenerateDescription: seo.autoDescription,
          autoSchemaFromBlocks: seo.autoSchema,
        },
      });
      const where = res.htaccessPath ? ` .htaccess yenilendi: ${res.htaccessPath}.` : "";
      const fail = res.htaccessError ? ` Dosya yazılamadı: ${res.htaccessError}.` : "";
      setNotice(`SEO ayarları kaydedildi.${where}${fail} Nginx bu dosyayı okumaz.`);
      router.refresh();
    });
  };

  return (
    <div className="space-y-4">
      <header className="flex flex-wrap items-end justify-between gap-3 border-b border-[#E6E7EA] pb-3 dark:border-[#23262E]">
        <div>
          <h1 className="text-[18px] font-semibold">SEO</h1>
          <p className="text-[12px] text-[#5F6570] dark:text-[#8C9099]">
            {siteName} için motor ayarları ve kayıtlı skor özeti. Sayfa başlığı stüdyoda düzenlenir.
          </p>
        </div>
        <div className="flex items-center gap-2">
          <nav className="flex gap-1">
            <TabButton active={tab === "summary"} onClick={() => setTab("summary")}>
              Durum
            </TabButton>
            <TabButton active={tab === "settings"} onClick={() => setTab("settings")}>
              Ayarlar
            </TabButton>
          </nav>
          {tab === "settings" ? (
            <button
              type="button"
              disabled={pending}
              onClick={save}
              className="rounded-md bg-[#14151A] px-3 py-1.5 text-[12px] font-semibold text-white disabled:opacity-50 dark:bg-[#F3F4F6] dark:text-[#14151A]"
            >
              {pending ? "Kaydediliyor" : "Kaydet"}
            </button>
          ) : null}
        </div>
      </header>
      {notice ? <p className="text-[12px] text-emerald-800 dark:text-emerald-400">{notice}</p> : null}
      {seo.searchIndexing === false ? (
        <p className="rounded-md border border-amber-300 bg-amber-50 px-3 py-2 text-[12px] text-amber-950 dark:border-amber-700 dark:bg-amber-950/40 dark:text-amber-100">
          Arama indeksi kapalı. Sayfalar noindex, site haritası boş, robots.txt tüm siteyi kapatır.
        </p>
      ) : null}
      {tab === "summary" ? <SummaryView summary={summary} /> : <SettingsView seo={seo} patch={patch} />}
    </div>
  );
}

function TabButton({
  active,
  onClick,
  children,
}: {
  active: boolean;
  onClick: () => void;
  children: React.ReactNode;
}) {
  return (
    <button
      type="button"
      onClick={onClick}
      className={`rounded-md px-2.5 py-1 text-[12px] ${
        active
          ? "bg-[#14151A] text-white dark:bg-[#F3F4F6] dark:text-[#14151A]"
          : "border border-[#E6E7EA] text-[#5C5F66] dark:border-[#23262E]"
      }`}
    >
      {children}
    </button>
  );
}

function SummaryView({ summary }: { summary: SeoSummary }) {
  const metrics = [
    { label: "Ortalama skor", value: String(summary.average), hint: "/100" },
    { label: "Yayında", value: String(summary.published), hint: `${summary.total} kayıt` },
    { label: "Eksik meta", value: String(summary.missingMeta + summary.missingDescription), hint: "uzun başlık veya eksik açıklama" },
    { label: "noindex yayın", value: String(summary.noIndexPublished), hint: "indekslenmez" },
  ];
  return (
    <div className="space-y-4">
      <div className="grid grid-cols-2 divide-y divide-[#E6E7EA] overflow-hidden rounded-lg border border-[#E6E7EA] bg-white dark:divide-[#23262E] dark:border-[#23262E] dark:bg-[#15171C] lg:grid-cols-4 lg:divide-x lg:divide-y-0">
        {metrics.map((item) => (
          <div key={item.label} className="p-4">
            <div className="text-[11px] text-[#5F6570] dark:text-[#8C9099]">{item.label}</div>
            <div className="mt-1 text-xl font-semibold tabular-nums">
              {item.value}
              <span className="ml-1 text-[11px] font-normal text-[#5F6570] dark:text-[#8C9099]">{item.hint}</span>
            </div>
          </div>
        ))}
      </div>
      <div className="grid gap-4 lg:grid-cols-2">
        <section className="rounded-lg border border-[#E6E7EA] bg-white p-4 dark:border-[#23262E] dark:bg-[#15171C]">
          <h2 className="text-[13px] font-semibold">Harf dağılımı</h2>
          <ul className="mt-3 space-y-2 text-[12px]">
            {(
              [
                ["A", summary.grades.a, "90+"],
                ["B", summary.grades.b, "75–89"],
                ["C", summary.grades.c, "60–74"],
                ["D", summary.grades.d, "60 altı"],
              ] as const
            ).map(([letter, count, range]) => (
              <li key={letter} className="flex items-center justify-between">
                <span>
                  {letter} <span className="text-[#5F6570] dark:text-[#8C9099]">{range}</span>
                </span>
                <span className="tabular-nums">{count}</span>
              </li>
            ))}
          </ul>
          <p className="mt-3 text-[11px] text-[#5F6570] dark:text-[#8C9099]">
            Görselsiz yayın {summary.missingImage} · odak kelimesiz {summary.missingKeyword} · kısa metin {summary.thin}
          </p>
        </section>
        <section className="rounded-lg border border-[#E6E7EA] bg-white p-4 dark:border-[#23262E] dark:bg-[#15171C]">
          <h2 className="text-[13px] font-semibold">Site kontrolleri</h2>
          <ul className="mt-3 space-y-2">
            {summary.checks.map((check) => (
              <li key={check.id} className="flex items-start justify-between gap-3 text-[12px]">
                <span>
                  <span className={check.ok ? "text-emerald-800 dark:text-emerald-400" : "text-amber-800"}>{check.ok ? "Tamam" : "Eksik"}</span>
                  <span className="ml-2">{check.label}</span>
                </span>
                <span className="max-w-[46%] truncate text-right text-[#5F6570] dark:text-[#8C9099]">{check.detail}</span>
              </li>
            ))}
          </ul>
          <div className="mt-3 flex flex-wrap gap-2 text-[11px]">
            <a className="underline" href="/sitemap.xml" target="_blank" rel="noreferrer">
              sitemap.xml
            </a>
            <a className="underline" href="/llms.txt" target="_blank" rel="noreferrer">
              llms.txt
            </a>
            <a className="underline" href="/robots.txt" target="_blank" rel="noreferrer">
              robots.txt
            </a>
          </div>
        </section>
      </div>
      <section className="overflow-hidden rounded-lg border border-[#E6E7EA] bg-white dark:border-[#23262E] dark:bg-[#15171C]">
        <div className="border-b border-[#E6E7EA] px-4 py-2 text-[12px] font-semibold dark:border-[#23262E]">
          Önce bakılacak kayıtlar
        </div>
        {summary.rows.length === 0 ? (
          <p className="px-4 py-6 text-[12px] text-[#5F6570] dark:text-[#8C9099]">Açık boşluk yok.</p>
        ) : (
          <ul className="divide-y divide-[#E6E7EA] dark:divide-[#23262E]">
            {summary.rows.map((row) => (
              <li key={row.id} className="flex flex-wrap items-center justify-between gap-2 px-4 py-2.5">
                <div>
                  <Link
                    href={`/admin/contents?id=${row.id}&type=${row.type}`}
                    className="text-[13px] font-medium hover:underline"
                  >
                    {row.title}
                  </Link>
                  <p className="text-[11px] text-[#5F6570] dark:text-[#8C9099]">
                    {contentTypeLabel(row.type)} · /{row.slug} · {row.issues.join(" · ")}
                  </p>
                </div>
                <span className="tabular-nums text-[13px] font-semibold">{row.score}</span>
              </li>
            ))}
          </ul>
        )}
      </section>
    </div>
  );
}

function SettingsView({
  seo,
  patch,
}: {
  seo: SeoEngineSettings;
  patch: (next: Partial<SeoEngineSettings>) => void;
}) {
  return (
    <div className="grid gap-4 lg:grid-cols-2">
      <section className="space-y-3 rounded-lg border border-[#E6E7EA] bg-white p-4 dark:border-[#23262E] dark:bg-[#15171C]">
        <h2 className="text-[13px] font-semibold">Kalıcı bağlantı</h2>
        <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
          Yapı
          <select
            className={`${fieldClass} mt-1`}
            value={seo.permalinkStructure ?? "postname"}
            onChange={(e) => patch({ permalinkStructure: e.target.value as PermalinkStructure })}
          >
            <option value="postname">Yazı adı — /yazi-adi</option>
            <option value="plain">Düz — /yazi-adi</option>
            <option value="dayname">Gün ve ad — /2026/11/10/yazi-adi</option>
            <option value="monthname">Ay ve ad — /2026/11/yazi-adi</option>
            <option value="numeric">Sayısal — /arsiv/123/yazi-adi</option>
          </select>
        </label>
        <p className="text-[11px] text-[#5F6570] dark:text-[#8C9099]">Kayıt .htaccess dosyasını yeniler. Nginx bu dosyayı okumaz.</p>
        <h2 className="text-[13px] font-semibold">Başlık ve açıklama</h2>
        <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
          Başlık şablonu
          <input className={`${fieldClass} mt-1 font-mono`} value={seo.titleTemplate} onChange={(e) => patch({ titleTemplate: e.target.value })} />
        </label>
        <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
          Ana sayfa şablonu
          <input className={`${fieldClass} mt-1 font-mono`} value={seo.homeTitleTemplate} onChange={(e) => patch({ homeTitleTemplate: e.target.value })} />
        </label>
        <div className="grid grid-cols-2 gap-2">
          <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
            Ayırıcı
            <input
              className={`${fieldClass} mt-1`}
              value={seo.titleSeparator ?? seo.separator}
              onChange={(e) => patch({ titleSeparator: e.target.value, separator: e.target.value })}
            />
          </label>
          <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
            En az kelime
            <input
              type="number"
              min={0}
              className={`${fieldClass} mt-1`}
              value={seo.minWordCount}
              onChange={(e) => patch({ minWordCount: Number(e.target.value) || 0 })}
            />
          </label>
        </div>
        <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
          Açıklama kaynağı
          <select
            className={`${fieldClass} mt-1`}
            value={seo.descriptionFallback}
            onChange={(e) => patch({ descriptionFallback: e.target.value as SeoEngineSettings["descriptionFallback"] })}
          >
            <option value="tldr">Kısa yanıt</option>
            <option value="excerpt">Özet</option>
            <option value="content">İlk paragraf</option>
          </select>
        </label>
        <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
          Varsayılan meta açıklama
          <textarea
            rows={3}
            className={`${fieldClass} mt-1`}
            value={seo.defaultMetaDescription ?? ""}
            onChange={(e) => patch({ defaultMetaDescription: e.target.value })}
          />
        </label>
      </section>
      <section className="space-y-3 rounded-lg border border-[#E6E7EA] bg-white p-4 dark:border-[#23262E] dark:bg-[#15171C]">
        <h2 className="text-[13px] font-semibold">Kimlik ve paylaşım</h2>
        <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
          Kurum adı
          <input className={`${fieldClass} mt-1`} value={seo.organizationName} onChange={(e) => patch({ organizationName: e.target.value })} />
        </label>
        <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
          Logo adresi
          <input className={`${fieldClass} mt-1`} value={seo.organizationLogo} onChange={(e) => patch({ organizationLogo: e.target.value })} />
        </label>
        <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
          Twitter
          <input className={`${fieldClass} mt-1`} value={seo.twitterHandle} onChange={(e) => patch({ twitterHandle: e.target.value })} placeholder="@site" />
        </label>
        <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
          Varsayılan paylaşım görseli
          <input className={`${fieldClass} mt-1`} value={seo.defaultOgImage} onChange={(e) => patch({ defaultOgImage: e.target.value })} />
        </label>
        <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
          Aynı kuruluş bağlantıları
          <textarea
            rows={3}
            className={`${fieldClass} mt-1`}
            value={seo.sameAs.join("\n")}
            onChange={(e) => patch({ sameAs: e.target.value.split("\n") })}
            placeholder="https://"
          />
        </label>
      </section>
      <section className="space-y-2 rounded-lg border border-[#E6E7EA] bg-white p-4 dark:border-[#23262E] dark:bg-[#15171C]">
        <h2 className="text-[13px] font-semibold">Motor</h2>
        {TOGGLES.map((rule) => (
          <label key={String(rule.key)} className="flex items-center justify-between gap-3 text-[12px]">
            <span>{rule.label}</span>
            <input
              type="checkbox"
              checked={Boolean(seo[rule.key])}
              onChange={(e) => patch({ [rule.key]: e.target.checked } as Partial<SeoEngineSettings>)}
            />
          </label>
        ))}
      </section>
      <section className="space-y-3 rounded-lg border border-[#E6E7EA] bg-white p-4 dark:border-[#23262E] dark:bg-[#15171C]">
        <h2 className="text-[13px] font-semibold">Sitemap ve robots</h2>
        <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
          Arama motoru indeksi
          <select
            className={`${fieldClass} mt-1`}
            value={seo.searchIndexing === false ? "off" : "on"}
            onChange={(e) => patch({ searchIndexing: e.target.value === "on" })}
          >
            <option value="on">Açık — site indekslenebilir</option>
            <option value="off">Kapalı — tüm site noindex</option>
          </select>
        </label>
        <p className="text-[11px] leading-relaxed text-[#5F6570] dark:text-[#8C9099]">
          Kapalıyken her sayfa noindex olur, site haritası boş döner ve robots.txt siteyi kapatır. Kopya veya deneme adresinde kapalı tutun; kaydı unutmayın.
        </p>
        <div className="flex flex-wrap gap-2">
          {TYPES.map((type) => {
            const on = seo.sitemapTypes.includes(type.id);
            return (
              <button
                key={type.id}
                type="button"
                onClick={() =>
                  patch({
                    sitemapTypes: on
                      ? seo.sitemapTypes.filter((item) => item !== type.id)
                      : [...seo.sitemapTypes, type.id],
                  })
                }
                className={`rounded-md px-2 py-1 text-[11px] ${
                  on ? "bg-blue-600 text-white" : "border border-[#E6E7EA] dark:border-[#23262E]"
                }`}
              >
                {type.label}
              </button>
            );
          })}
        </div>
        <WebmasterPanel value={seo.verification ?? {}} onChange={(verification) => patch({ verification })} />
        <BotPolicyPanel policy={seo.botPolicy ?? {}} onChange={(botPolicy) => patch({ botPolicy })} />
        <label className="block text-[11px] text-[#5F6570] dark:text-[#8C9099]">
          robots.txt ek satırları
          <textarea
            rows={4}
            className={`${fieldClass} mt-1 font-mono`}
            value={seo.robotsTxtExtra}
            onChange={(e) => patch({ robotsTxtExtra: e.target.value })}
          />
        </label>
      </section>
    </div>
  );
}
